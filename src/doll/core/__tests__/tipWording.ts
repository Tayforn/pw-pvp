// =========================================================
// Свідома відмінність тексту тултіпа від calc: русизм Хелпера «Требуємий/Требуєма …»
// у вимогах речі pvp пише як «Потрібний/Потрібна …». Еталони (golden/tips.json)
// лишаються текстом незміненого calc, а тести тултіпа переводять їх цим словником —
// решта рядків має збігатися байт у байт.
// =========================================================

const WORDING: Array<[RegExp, string]> = [
  [/^Требуємий рівень:/, 'Потрібний рівень:'],
  [/^Требуєма Сила:/, 'Потрібна сила:'],
  [/^Требуєма Спритність:/, 'Потрібна спритність:'],
  [/^Требуємий Інтелект:/, 'Потрібний інтелект:'],
  [/^Требуєма репутація:/, 'Потрібна репутація:'],
];

/** Рядок еталона calc → як його пише pvp. */
export function pvpWording(line: string): string {
  return WORDING.reduce((t, [re, to]) => t.replace(re, to), line);
}
