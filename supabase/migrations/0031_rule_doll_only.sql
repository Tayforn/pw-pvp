-- Фул-рандом — лише персонажем з ляльки (ручної анкети на сторінці заявки
-- більше немає). Оновлює рядок про анкету в стандартному блоці реєстрації
-- (rule_items.reg_block, засіяний 0027).
--
-- Міняє лише стандартний рядок: якщо суперадмін уже переписав його у вкладці
-- «Правила», replace нічого не знайде і текст лишиться як є. Знімки правил
-- уже створених турнірів не чіпає.

update rule_items
set text_player = replace(
  text_player,
  'Анкета спорядження заповнюється чесно — адмін перевіряє спорядження в грі. Неправдиві дані — дискваліфікація, місце займає гравець із резерву.',
  'Заявка — лише персонажем з ляльки: лялька має відповідати спорядженню в грі, адмін це перевіряє. Неправдиві дані — дискваліфікація, місце займає гравець із резерву.'
)
where key = 'reg_block';
