-- «Аспд»-сету немає: для аспдшників швидкість атаки — це Головний сет. Третій
-- вид свап-сету тепер лише «Спів» (−30 % часу співу). Оновлює рядок про пороги
-- сетів у стандартному блоці реєстрації (rule_items.reg_block, засіяний 0027).
--
-- Міняє лише стандартний рядок: якщо суперадмін уже переписав його у вкладці
-- «Правила», replace нічого не знайде і текст лишиться як є. Знімки правил
-- уже створених турнірів не чіпає.

update rule_items
set text_player = replace(
  text_player,
  'ПЗ-сет / ПА-сет / Спів-Аспід рахуються від порогів: сумарний ПЗ ≥ 30, ПА ≥ 30, швидкість атаки ≥ 3.33 уд/с або −30 % часу активації — усе без бафів.',
  'ПЗ-сет / ПА-сет / Спів-сет рахуються від порогів: сумарний ПЗ ≥ 30, ПА ≥ 30, −30 % часу співу — усе без бафів. Окремого аспд-сету немає: швидкість атаки — це Головний сет.'
)
where key = 'reg_block';
